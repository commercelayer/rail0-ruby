#!/usr/bin/env ruby
# frozen_string_literal: true

#
# Code generation for the RAIL0 Ruby SDK.
#
# Generates two files from the gateway's OpenAPI schema:
#
#   lib/rail0/types.rb           — documentation-only Struct definitions for the
#                                  gateway's request/response schemas.
#   lib/rail0/dispute_reasons.rb — the dispute-reason dictionary (runtime constants):
#                                  the DisputeOpenReason / DisputeCloseReason /
#                                  DisputeSystemCloseReason enums with their
#                                  x-enum-descriptions and x-enum-bytes32.
# The resource classes (lib/rail0/resources/)
# and the HTTP/signing layers are hand-maintained and are NOT generated: methods
# return plain Hashes (symbol keys), so these Structs are reference documentation,
# not runtime types. This mirrors the rail0-go generator, which likewise generates
# only its types file from the same schema.
#
# Schema source (in priority order):
#   1. RAIL0_SCHEMA_PATH env var — absolute path to a local openapi.json
#   2. Default: ../rail0-gateway/docs/openapi.json (sibling repo on the filesystem)
#
# Run from the repository root:
#   ruby gen/generate.rb

require "json"

# ---------------------------------------------------------------------------
# Schema path resolution
# ---------------------------------------------------------------------------

default_schema_path = File.expand_path("../../rail0-gateway/docs/openapi.json", __dir__)
schema_path = ENV.fetch("RAIL0_SCHEMA_PATH", default_schema_path)

unless File.exist?(schema_path)
  abort "ERROR: OpenAPI schema not found at #{schema_path}\n" \
        "Set RAIL0_SCHEMA_PATH to the correct path or place the schema at the default location."
end

schema  = JSON.parse(File.read(schema_path, encoding: "UTF-8"))
schemas = schema.dig("components", "schemas") || {}

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def ref_name(ref)
  ref.split("/").last
end

# A short Ruby-flavoured type hint for a property, derived from its OpenAPI type.
def type_comment(prop_def)
  if prop_def.key?("$ref")
    ref_name(prop_def["$ref"])
  elsif prop_def.key?("allOf")
    ref_entry = prop_def["allOf"].find { |e| e.key?("$ref") }
    ref_entry ? ref_name(ref_entry["$ref"]) : nil
  elsif prop_def.key?("anyOf")
    # A nullable reference (`anyOf: [{$ref}, …, {type: null}]`): name the refs, then nil.
    hints = prop_def["anyOf"].map { |e| e.key?("$ref") ? ref_name(e["$ref"]) : (e["type"] == "null" ? "nil" : e["type"]) }
    hints.compact.join(" | ")
  else
    case prop_def["type"]
    when "integer" then "Integer"
    when "number"  then "Numeric"
    when "boolean" then "Boolean"
    when "string"  then "String"
    when "array"   then "Array"
    when "object"  then "Hash"
    end
  end
end

def member_comment(prop_def, type_hint)
  parts = []
  parts << type_hint if type_hint
  desc = prop_def["description"]
  parts << desc if desc && !desc.empty?
  parts.empty? ? nil : parts.join(" — ")
end

# The gateway's generic "Error" schema maps to Rail0::Types::ApiErrorBody so it
# does not collide with Rail0::ApiError (the raised exception).
def struct_name(schema_name)
  schema_name == "Error" ? "ApiErrorBody" : schema_name
end

# ---------------------------------------------------------------------------
# Generate lib/rail0/types.rb
# ---------------------------------------------------------------------------

object_schemas = schemas.select { |_, v| v["type"] == "object" }

lines = []
lines << "# frozen_string_literal: true"
lines << ""
lines << "# Code generated by gen/generate.rb — DO NOT EDIT."
lines << "# Re-run `ruby gen/generate.rb` after updating the gateway OpenAPI schema."
lines << "#"
lines << "# Source: rail0-gateway/docs/openapi.json"
lines << "#"
lines << "# These Structs document the gateway's request/response shapes. They are"
lines << "# reference only — SDK methods return plain Hashes with symbol keys."
lines << ""
lines << "module Rail0"
lines << "  module Types"

# The output must pass the repo's own rubocop as written, not after a hand-run -a: a blank
# line between Structs, none at the module body's start.
object_schemas.each_with_index do |(name, schema_def), index|
  ruby_name   = struct_name(name)
  description = schema_def["description"]
  properties  = schema_def["properties"] || {}

  lines << "" unless index.zero?

  if description && !description.empty?
    current = "    # "
    description.split.each do |word|
      if current.length + word.length + 1 > 104
        lines << current.rstrip
        current = "    # #{word}"
      else
        current += (current == "    # " ? word : " #{word}")
      end
    end
    lines << current.rstrip
  end

  if properties.empty?
    lines << "    #{ruby_name} = Struct.new(keyword_init: true)"
    next
  end

  lines << "    #{ruby_name} = Struct.new("
  entries = properties.map { |pn, pd| [pn, member_comment(pd, type_comment(pd))] }
  pad_width = entries.map { |pn, _| pn.length }.max + 3
  entries.each do |prop_name, inline_desc|
    padded  = ":#{prop_name},".ljust(pad_width)
    comment = inline_desc ? " # #{inline_desc}" : ""
    lines << "      #{padded}#{comment}".rstrip
  end
  lines << "      keyword_init: true"
  lines << "    )"
end

lines << "  end"
lines << "end"
lines << ""

types_path = File.expand_path("../lib/rail0/types.rb", __dir__)
File.write(types_path, lines.join("\n"))
puts "Generated #{types_path}"

# ---------------------------------------------------------------------------
# Generate lib/rail0/dispute_reasons.rb
# ---------------------------------------------------------------------------
#
# The gateway publishes its dispute-reason dictionary as three string-enum schemas whose
# `enum`, `x-enum-descriptions` and `x-enum-bytes32` arrays line up index by index. Those
# arrays are the whole source of truth: the bytes32 is copied, never recomputed here
# (keccak256 is not in the stdlib, and the gateway's value is the one it accepts). The
# spec suite re-derives each bytes32 with the `eth` gem as a cross-check.

DISPUTE_REASON_SCHEMAS = {
  "OPEN" => ["DisputeOpenReason", "Reasons a payer may open a dispute with (Payments#dispute_prepare)."],
  "CLOSE" => ["DisputeCloseReason", "Reasons a payer may close a dispute with (Payments#close_dispute_prepare)."],
  "SYSTEM" => ["DisputeSystemCloseReason",
               "Close reasons the protocol records on its own — read back on a dispute, never accepted from a caller."]
}.freeze

# The [code, description, bytes32] triples of one reason schema, or abort when the schema
# is missing or its three arrays disagree in length (a silently shortened list would
# drop a reason rather than fail the build).
def reason_entries(schemas, schema_name)
  schema_def = schemas[schema_name] or abort "ERROR: #{schema_name} not found in the OpenAPI schema"
  codes        = schema_def["enum"] || []
  descriptions = schema_def["x-enum-descriptions"] || []
  bytes32s     = schema_def["x-enum-bytes32"] || []
  unless !codes.empty? && codes.length == descriptions.length && codes.length == bytes32s.length
    abort "ERROR: #{schema_name}: enum, x-enum-descriptions and x-enum-bytes32 must be non-empty and the same length"
  end
  bad = bytes32s.reject { |b| b.match?(/\A0x\h{64}\z/) }
  abort "ERROR: #{schema_name}: malformed x-enum-bytes32 #{bad.inspect}" unless bad.empty?

  codes.zip(descriptions, bytes32s)
end

reason_lines = []
reason_lines << "# frozen_string_literal: true"
reason_lines << ""
reason_lines << "# Code generated by gen/generate.rb — DO NOT EDIT."
reason_lines << "# Re-run `ruby gen/generate.rb` after updating the gateway OpenAPI schema."
reason_lines << "#"
reason_lines << "# Source: rail0-gateway/docs/openapi.json — components.schemas.DisputeOpenReason,"
reason_lines << "# DisputeCloseReason and DisputeSystemCloseReason (enum, x-enum-descriptions and"
reason_lines << "# x-enum-bytes32, aligned by index)."
reason_lines << ""
reason_lines << "module Rail0"
reason_lines << "  # The gateway's dispute-reason dictionary. On-chain a dispute reason is a bytes32,"
reason_lines << "  # keccak256(\"rail0.dispute.<code>\"); the dispute prepares take either the code or"
reason_lines << "  # exactly that bytes32, and refuse anything else 422 unknown_dispute_reason. A"
reason_lines << "  # dispute read back carries `reason_code`/`reason_description` (and the close_"
reason_lines << "  # counterparts) already decoded by the gateway; these constants are for building a"
reason_lines << "  # picker, validating input before a round trip, or decoding a raw bytes32."
reason_lines << "  module DisputeReasons"
reason_lines << "    # One dictionary entry: the code the API speaks, its English description and the"
reason_lines << "    # bytes32 the contract stores."
reason_lines << "    Reason = Struct.new(:code, :description, :bytes32, keyword_init: true)"
reason_lines << ""
reason_lines << "    # What the gateway reports as the description of a bytes32 outside the dictionary."
reason_lines << "    UNRECOGNISED_DESCRIPTION = \"Unrecognised reason\""
DISPUTE_REASON_SCHEMAS.each do |const, (schema_name, comment)|
  reason_lines << ""
  reason_lines << "    # #{comment}"
  reason_lines << "    #{const} = ["
  entries = reason_entries(schemas, schema_name)
  entries.each_with_index do |(code, description, bytes32), i|
    reason_lines << "      Reason.new("
    reason_lines << "        code: #{code.to_s.inspect},"
    reason_lines << "        description: #{description.to_s.inspect},"
    reason_lines << "        bytes32: #{bytes32.downcase.inspect}"
    reason_lines << "      ).freeze#{',' unless i == entries.length - 1}"
  end
  reason_lines << "    ].freeze"
end
# Hand-written lookups, emitted verbatim (re-indented into the module body).
<<~RUBY.each_line { |l| reason_lines << (l.strip.empty? ? "" : "    #{l.chomp}") }

    # The lists by kind, for the lookups below.
    KINDS = { open: OPEN, close: CLOSE, system: SYSTEM }.freeze

    # The entries of one kind (:open, :close or :system).
    # @param kind [Symbol, String]
    # @return [Array<Reason>]
    # @raise [ArgumentError] for any other kind.
    def self.all(kind)
      KINDS.fetch(kind.to_sym) { raise ArgumentError, "unknown dispute reason kind: \#{kind.inspect}" }
    end

    # The codes of one kind, in dictionary order.
    # @param kind [Symbol, String]
    # @return [Array<String>]
    def self.codes(kind)
      all(kind).map(&:code)
    end

    # The entry of +kind+ that +value+ names — a code ("not_received" or :not_received)
    # or exactly its bytes32 (0x-hex, either case) — or nil. Lookups are per kind
    # because the lists overlap: "other" is both an open and a close reason, with one
    # bytes32.
    # @param kind [Symbol, String]
    # @param value [String, Symbol, nil]
    # @return [Reason, nil]
    def self.find(kind, value)
      return nil if value.nil?

      needle = value.to_s
      all(kind).find { |r| r.code == needle || r.bytes32.casecmp?(needle) }
    end

    # Whether the dispute prepare of +kind+ (:open or :close) would accept +value+.
    # :system is never accepted from a caller, so it always answers false.
    # @param kind [Symbol, String]
    # @param value [String, Symbol, nil]
    # @return [Boolean]
    def self.valid?(kind, value)
      kind.to_sym != :system && !find(kind, value).nil?
    end

    # The description the gateway would give +value+ as a +kind+ reason, or
    # {UNRECOGNISED_DESCRIPTION} when it is not in that list.
    # @param kind [Symbol, String]
    # @param value [String, Symbol, nil]
    # @return [String]
    def self.description_for(kind, value)
      find(kind, value)&.description || UNRECOGNISED_DESCRIPTION
    end
RUBY
reason_lines << "  end"
reason_lines << "end"
reason_lines << ""

reasons_path = File.expand_path("../lib/rail0/dispute_reasons.rb", __dir__)
File.write(reasons_path, reason_lines.join("\n"))
puts "Generated #{reasons_path}"
puts "Schema:   #{schema_path}"
puts "Done."
